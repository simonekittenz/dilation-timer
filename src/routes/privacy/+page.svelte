<h1>Privacy ✿</h1>
<p class="muted updated">Dilation timer · last updated 21 October 2026</p>

<section class="card">
	<h2>The short version</h2>
	<p>
		Your information stays on your phone or computer. There are no accounts and no ads. Nothing you
		enter (your surgery date, schedule, sessions or history) is ever sent to me or to anyone else.
		The Android and iPhone apps contain no analytics or tracking at all. The website counts visits
		anonymously, as explained below.
	</p>
</section>

<section class="card">
	<h2>What the app keeps</h2>
	<p>
		Your settings, your schedule, your session history and any session that is running are saved on
		your own device, in the app's storage (in a web browser: the browser's local storage). It is
		kept so the app can show your schedule and carry on after you close it. Deleting the app, or
		clearing the browser's data for this website, removes it.
	</p>
	<p>
		<strong>Settings → Save backup</strong> writes a file with that information to a place you choose.
		The app does not upload it anywhere; where it goes is up to you.
	</p>
	<p>
		Like any app, Android may include an app's data in your phone's own backup to your Google
		account, if you have that turned on. That is a setting of your phone, not something this app
		sends.
	</p>
</section>

<section class="card">
	<h2>What goes over the internet</h2>
	<ul>
		<li>
			<strong>The website</strong> sends you its pages and files, like any website. The company that hosts
			it (Vercel) can see the technical details every web server sees, such as your IP address and browser.
			I don't use them.
		</li>
		<li>
			<strong>Visit counts (the website only):</strong> the website uses Vercel Web Analytics to see how
			many people visit which pages. It uses no cookies and no accounts, and does not follow you between
			websites. For each page view it records the page address (never anything you typed), where you came
			from, your country or region, your device type and your browser and system. It cannot tell who you
			are, and it is not used for anything but counting. It is switched off for browsers that send "Do
			Not Track" or "Global Privacy Control", and it is not part of the Android or iPhone app, including
			the Google Play version.
		</li>
		<li>
			<strong>The Android app</strong>, when downloaded from the website, asks the website whether a
			newer version exists. This is an ordinary request that sends none of your information. The
			version from Google Play makes no requests at all, because Google Play does the updating.
		</li>
	</ul>
</section>

<section class="card">
	<h2>Permissions on Android</h2>
	<ul>
		<li>
			<strong>Notifications:</strong> to alert you when a timer ends, and to remind you of your sessions
			at the times you choose, even when the phone is locked.
		</li>
		<li>
			<strong>Alarms and reminders, and starting after a restart:</strong> so those alerts arrive on time,
			and are not lost if the phone restarts.
		</li>
		<li><strong>Keeping the screen awake:</strong> so the timer stays visible during a session.</li>
		<li><strong>Internet:</strong> for the update check above.</li>
	</ul>
	<p>The app does not ask for your location, contacts, camera, microphone, photos or files.</p>
</section>

<section class="card">
	<h2>Other apps' audio</h2>
	<p>
		When an alarm sounds, the app briefly lowers the volume of music or podcasts that are playing,
		and restores it afterwards. It does not listen to or record anything.
	</p>
</section>

<section class="card">
	<h2>Who it's for</h2>
	<p>
		This is a personal timer for adults, not medical advice, and it does not diagnose anything.
		Always follow the instructions of your own clinic. It is not meant for children.
	</p>
</section>

